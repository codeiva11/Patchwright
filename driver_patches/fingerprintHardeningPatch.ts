import { type Project } from "ts-morph";

// ---------------------------------------------------------------------------
// server/browserContext.ts
// ---------------------------------------------------------------------------
// Hardened opt-in fingerprint script. All replaced properties stay on the
// native prototype, remain non-enumerable, and use Proxy wrappers so
// Function.prototype.toString still reports native code. Canvas noise uses a
// stable per-profile seed instead of Math.random(), so a reload does not change
// the canvas hash.
export function patchFingerprintHardening(project: Project) {
	const sourceFile = project.addSourceFileAtPath("packages/playwright-core/src/server/browserContext.ts");
	const scriptFunction = (cfg: any): string => {
		const lines = [
			"const nativeProto = Object.getPrototypeOf(navigator);",
			"const defineGetter = (target, prop, getter) => {",
			"  try {",
			"    const descriptor = Object.getOwnPropertyDescriptor(target, prop);",
			"    Object.defineProperty(target, prop, { get: getter, set: descriptor && descriptor.set, configurable: true, enumerable: descriptor ? descriptor.enumerable : false });",
			"  } catch (e) { }",
			"};",
			"if (typeof cfg.hardwareConcurrency === 'number') defineGetter(nativeProto, 'hardwareConcurrency', () => cfg.hardwareConcurrency);",
			"if (typeof cfg.deviceMemory === 'number') defineGetter(nativeProto, 'deviceMemory', () => cfg.deviceMemory);",
			"if (cfg.platform) defineGetter(nativeProto, 'platform', () => cfg.platform);",
			"if (cfg.userAgent) defineGetter(nativeProto, 'userAgent', () => cfg.userAgent);",
			"const seen = new WeakSet();",
			"const hookMethod = (proto, name, wrap) => {",
			"  if (!proto || typeof proto[name] !== 'function') return;",
			"  const original = proto[name];",
			"  if (seen.has(original)) return;",
			"  seen.add(original);",
			"  const proxy = new Proxy(original, { apply(target, thisArg, args) { return wrap(target, thisArg, args); } });",
			"  try { Object.defineProperty(proto, name, { value: proxy, configurable: true, writable: true, enumerable: false }); } catch (e) { }",
			"};",
			"if (cfg.webglVendor || cfg.webglRenderer) {",
			"  const hookGl = proto => hookMethod(proto, 'getParameter', (target, thisArg, args) => {",
			"    const parameter = args[0];",
			"    if (parameter === 0x9245 && cfg.webglVendor) return cfg.webglVendor;",
			"    if (parameter === 0x9246 && cfg.webglRenderer) return cfg.webglRenderer;",
			"    return Reflect.apply(target, thisArg, args);",
			"  });",
			"  try { hookGl(window.WebGLRenderingContext && window.WebGLRenderingContext.prototype); hookGl(window.WebGL2RenderingContext && window.WebGL2RenderingContext.prototype); } catch (e) { }",
			"}",
			"if (cfg.canvasNoise) {",
			"  const seed = Number.isFinite(Number(cfg.canvasSeed)) ? (Number(cfg.canvasSeed) >>> 0) : 0x9e3779b9;",
			"  const noiseAt = (x, y) => {",
			"    let h = (x * 374761393 + y * 668265263 + seed * 69069) & 0x7fffffff;",
			"    h = (h ^ (h >>> 13)) * 1274126177;",
			"    return ((h ^ (h >>> 16)) & 0x7fffffff) / 0x7fffffff;",
			"  };",
			"  const noisify = imageData => {",
			"    const data = imageData.data;",
			"    for (let i = 0; i < data.length; i += 4) {",
			"      const pixel = i >> 2;",
			"      if (noiseAt(pixel % imageData.width, (pixel / imageData.width) | 0) < 0.08) data[i] = data[i] ^ 1;",
			"    }",
			"    return imageData;",
			"  };",
			"  const contextProto = CanvasRenderingContext2D.prototype;",
			"  const originalGetImageData = contextProto.getImageData;",
			"  hookMethod(contextProto, 'getImageData', (target, thisArg, args) => noisify(Reflect.apply(target, thisArg, args)));",
			"  const cloneNoisified = canvas => {",
			"    const copy = document.createElement('canvas');",
			"    copy.width = canvas.width;",
			"    copy.height = canvas.height;",
			"    const copyContext = copy.getContext('2d');",
			"    copyContext.drawImage(canvas, 0, 0);",
			"    const image = originalGetImageData.call(copyContext, 0, 0, copy.width, copy.height);",
			"    noisify(image);",
			"    copyContext.putImageData(image, 0, 0);",
			"    return copy;",
			"  };",
			"  hookMethod(HTMLCanvasElement.prototype, 'toDataURL', (target, thisArg, args) => {",
			"    try { if (thisArg.width && thisArg.height) thisArg = cloneNoisified(thisArg); } catch (e) { }",
			"    return Reflect.apply(target, thisArg, args);",
			"  });",
			"  hookMethod(HTMLCanvasElement.prototype, 'toBlob', (target, thisArg, args) => {",
			"    try { if (thisArg.width && thisArg.height) thisArg = cloneNoisified(thisArg); } catch (e) { }",
			"    return Reflect.apply(target, thisArg, args);",
			"  });",
			"  if (window.OffscreenCanvasRenderingContext2D) hookMethod(window.OffscreenCanvasRenderingContext2D.prototype, 'getImageData', (target, thisArg, args) => noisify(Reflect.apply(target, thisArg, args)));",
			"}",
			"if (cfg.permissions && window.Permissions && window.Permissions.prototype && window.Permissions.prototype.query) {",
			"  const permissionsProto = window.Permissions.prototype;",
			"  const originalQuery = permissionsProto.query;",
			"  const align = (status, stateOverride) => {",
			"    const aligned = Object.create(Object.getPrototypeOf(status));",
			"    for (const key of ['state', 'name', 'onchange']) {",
			"      try {",
			"        Object.defineProperty(aligned, key, {",
			"          get: () => (key === 'state' && stateOverride ? stateOverride : status[key]),",
			"          set: key === 'onchange' ? value => { status.onchange = value; } : undefined,",
			"          configurable: true,",
			"          enumerable: false,",
			"        });",
			"      } catch (e) { }",
			"    }",
			"    return aligned;",
			"  };",
			"  const proxy = new Proxy(originalQuery, {",
			"    apply(target, thisArg, args) {",
			"      const descriptor = args[0];",
			"      const run = () => Promise.resolve(Reflect.apply(target, thisArg, args)).then(status => {",
			"        const name = descriptor && descriptor.name;",
			"        if (cfg.permissions.granted && cfg.permissions.granted.includes(name)) return align(status, 'granted');",
			"        if (cfg.permissions.denied && cfg.permissions.denied.includes(name)) return align(status, 'denied');",
			"        if (name === 'notifications' && cfg.permissions.alignNotifications !== false) {",
			"          const notificationState = typeof Notification !== 'undefined' ? Notification.permission : undefined;",
			"          if (notificationState && notificationState !== status.state) return align(status, notificationState);",
			"        }",
			"        return status;",
			"      });",
			"      return cfg.permissions.delay ? new Promise(resolve => setTimeout(() => resolve(run()), cfg.permissions.delay)) : run();",
			"    },",
			"  });",
			"  try { Object.defineProperty(permissionsProto, 'query', { value: proxy, configurable: true, writable: true, enumerable: false }); } catch (e) { }",
			"}",
		];
		return "(function(){\n'use strict';\nconst cfg = " + JSON.stringify(cfg) + ";\n" + lines.join("\n") + "\n})();";
	};
	const target = sourceFile.getFunctionOrThrow("patchwrightFingerprintScript");
	target.setBodyText("return fingerprintScript(cfg);");
	sourceFile.addStatements("const fingerprintScript = " + scriptFunction.toString() + ";");
}
